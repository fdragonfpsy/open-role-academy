import { competencySchema, roleSchema, type Competency, type Role } from '../content/schemas';
import type { ContentBundle } from './bundle';

const LEVEL_SHORT: Record<string, string> = { foundation: 'F', practitioner: 'P', advanced: 'A' };

/**
 * Render docs/FRAMEWORK.md from the role and competency YAML (pure function).
 * Invalid files are skipped here; the content validator reports them.
 */
export function renderFramework(bundle: ContentBundle): string {
  const roles: Role[] = bundle.roles
    .map((f) => roleSchema.safeParse(f.data))
    .flatMap((r) => (r.success ? [r.data] : []))
    .sort((a, b) => (a.kind === b.kind ? a.id.localeCompare(b.id) : a.kind === 'core' ? -1 : 1));
  const comps = new Map<string, Competency>(
    bundle.competencies
      .map((f) => competencySchema.safeParse(f.data))
      .flatMap((r) => (r.success ? [[r.data.id, r.data] as const] : [])),
  );
  const title = (id: string) => comps.get(id)?.title.en ?? id;
  const lines: string[] = [
    '# Competency framework',
    '',
    '<!-- Generated by `npm run docs:framework` from src/content/roles and src/content/competencies. Do not edit by hand. -->',
    '',
    'Targets per **role level** (the learner\'s self-rated level): F = Foundation, P = Practitioner, A = Advanced, — = not required. Priority 1 = most important.',
    '',
    '## Overview: role × competency',
    '',
  ];
  const allIds = [...comps.values()]
    .sort((a, b) => (a.track === b.track ? a.id.localeCompare(b.id) : a.track === 'core' ? -1 : 1))
    .map((c) => c.id);
  lines.push(`| Competency | Track | ${roles.map((r) => r.id).join(' | ')} |`);
  lines.push(`|---|---|${roles.map(() => '---').join('|')}|`);
  for (const id of allIds) {
    const cells = roles.map((r) => {
      const rc = r.competencies.find((c) => c.id === id);
      if (!rc) return '';
      const t = rc.targets;
      return [t.foundation, t.practitioner, t.advanced].map((l) => (l ? LEVEL_SHORT[l] : '—')).join('/');
    });
    lines.push(`| ${title(id)} | ${comps.get(id)?.track ?? ''} | ${cells.join(' | ')} |`);
  }
  for (const r of roles) {
    lines.push('', `## ${r.title.en} (\`${r.id}\`, ${r.kind}, ${r.status})`, '', r.summary.en, '');
    lines.push('| Competency | Track | Priority | Foundation | Practitioner | Advanced | Prerequisites |');
    lines.push('|---|---|---|---|---|---|---|');
    const sorted = [...r.competencies].sort((a, b) => a.priority - b.priority || a.id.localeCompare(b.id));
    for (const rc of sorted) {
      const c = comps.get(rc.id);
      const t = rc.targets;
      const fmt = (l: string | null) => (l ? (LEVEL_SHORT[l] ?? l) : '—');
      lines.push(
        `| ${title(rc.id)} | ${c?.track ?? '?'} | ${rc.priority} | ${fmt(t.foundation)} | ${fmt(t.practitioner)} | ${fmt(t.advanced)} | ${(c?.prerequisites ?? []).join(', ') || '—'} |`,
      );
    }
  }
  return `${lines.join('\n')}\n`;
}
